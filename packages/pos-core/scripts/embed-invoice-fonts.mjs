// Regenerates src/print/invoiceFonts.ts from @fontsource-variable/cairo (run: npm run fonts:embed -w @moto/pos-core).
// Fonts are embedded as base64 so printed HTML is self-contained (Electron prints outerHTML from a data: URL).
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve('@fontsource-variable/cairo/package.json'));
const version = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8')).version;
const b64 = (file) => readFileSync(join(pkgDir, 'files', file)).toString('base64');

const out = `// Generated by scripts/embed-invoice-fonts.mjs from @fontsource-variable/cairo@${version}. Do not edit.
// Cairo is licensed under the SIL Open Font License 1.1 (https://openfontlicense.org).
export const CAIRO_ARABIC_WOFF2 = '${b64('cairo-arabic-wght-normal.woff2')}';
export const CAIRO_LATIN_WOFF2 = '${b64('cairo-latin-wght-normal.woff2')}';
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'print', 'invoiceFonts.ts');
writeFileSync(target, out);
console.log(`wrote ${target} (${Math.round(out.length / 1024)} KB)`);
