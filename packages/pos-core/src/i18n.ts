const dict: Record<Locale, PosTranslations> = { ar: posAr, en: posEn };

export const PosLocaleContext = React.createContext<Locale>('ar');

export function usePosT() {
  const locale = React.useContext(PosLocaleContext);
  const d = dict[locale];
  const tx = React.useCallback((t: LocalizedText | null | undefined) => txShared(t, locale), [locale]);
  return { p: d, tx, locale, isRtl: locale === 'ar', dir: locale === 'ar' ? ('rtl' as const) : ('ltr' as const) };
}

export function formatMoney(value: number, locale: Locale, symbol: LocalizedText = { ar: 'ج.م', en: 'EGP' }, decimals = 2): string {
  const n = new Intl.NumberFormat('en-US', { minimumFractionDigits: decimals, maximumFractionDigits: decimals }).format(value);
  return locale === 'ar' ? `${n} ${txShared(symbol, 'ar')}` : `${txShared(symbol, 'en')} ${n}`;
}

export function formatDateTime(iso: string): string {
  const d = new Date(iso);
  const pad = (n: number) => String(n).padStart(2, '0');
  return `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()} ${pad(d.getHours())}:${pad(d.getMinutes())}`;
}
